    fun english(text: String): String {
        english[text]?.let { return it }
        if (text.none { it in '\u4e00'..'\u9fff' }) return text
        for ((pattern, translated) in patterns) {
            val match = pattern.matchEntire(text) ?: continue
            return translated.replace("{0}", match.groupValues[1])
        }
        return text // App names, package names, technical identifiers and user content stay original.
    }
